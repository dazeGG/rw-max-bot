export type SeedNode = {
	code: string;
	title: string;
	type?: NodeType;
	text?: string;
	url?: string;
	target?: string;
	image?: string;
	file?: string;
	fileName?: string;
	hidden?: boolean;
	inactive?: boolean;
	children?: SeedNode[];
};

const link = (code: string, title: string, url: string): SeedNode =>
	({ code, title, type: 'link', url });

const goto = (code: string, title: string, target: string): SeedNode =>
	({ code, title, type: 'goto', target });

const ticketOffice = (code: string, location: string, text: string, maps: { yandex?: string; twoGis?: string; }): SeedNode => ({
	code,
	title: `Ж/Д касса ${location}`,
	text: `<b>Ж/Д касса ${location}</b>\n\n${text}`,
	children: [
		...maps.yandex ? [link(`${code}-yandex`, 'Открыть в Яндекс Картах', maps.yandex)] : [],
		...maps.twoGis ? [link(`${code}-2gis`, 'Открыть в 2ГИС', maps.twoGis)] : [],
	],
});

const picture = (code: string, title: string, image: string, inactive = false): SeedNode =>
	({ code, title, text: `<b>${title}</b>`, image: `generated/${image}`, inactive });

const faq = (code: string, question: string, answer: string): SeedNode =>
	({ code, title: question, text: `<b>${question}</b>\n\n${answer}` });

