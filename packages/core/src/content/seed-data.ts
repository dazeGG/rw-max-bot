export type SeedNode = {
	code: string;
	title: string;
	type?: NodeType;
	text?: string;
	url?: string;
	target?: string;
	image?: string;
	imageText?: string;
	tables?: ContentTable[];
	file?: string;
	fileName?: string;
	synonyms?: string[];
	hidden?: boolean;
	inactive?: boolean;
	children?: SeedNode[];
};

const link = (code: string, title: string, url: string, synonyms: string[] = []): SeedNode =>
	({ code, title, type: 'link', url, synonyms });

const goto = (code: string, title: string, target: string, synonyms: string[] = []): SeedNode =>
	({ code, title, type: 'goto', target, synonyms });

const ticketOffice = (code: string, location: string, text: string, maps: { yandex?: string; twoGis?: string; }, synonyms: string[]): SeedNode => ({
	code,
	title: `Ж/Д касса ${location}`,
	text: `<b>Ж/Д касса ${location}</b>\n\n${text}`,
	synonyms,
	children: [
		...maps.yandex ? [link(`${code}-yandex`, 'Открыть в Яндекс Картах', maps.yandex)] : [],
		...maps.twoGis ? [link(`${code}-2gis`, 'Открыть в 2ГИС', maps.twoGis)] : [],
	],
});

const picture = (code: string, title: string, image: string, synonyms: string[] = [], inactive = false): SeedNode =>
	({ code, title, text: `<b>${title}</b>`, image: `generated/${image}`, synonyms, inactive });

const faq = (code: string, question: string, answer: string, synonyms: string[]): SeedNode =>
	({ code, title: question, text: `<b>${question}</b>\n\n${answer}`, synonyms });

