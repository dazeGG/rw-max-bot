// Плоский список узлов с id в порядке обхода — для БД и для запуска без БД
export const flattenSeed = (tree: SeedNode = SEED_TREE): ContentNode[] => {
	const nodes: ContentNode[] = [];
	const ids = new Map<string, number>();
	const targets: Array<{ node: ContentNode; target: string; }> = [];

	const walk = (seed: SeedNode, parentId: number | null, sort: number) => {
		if (ids.has(seed.code)) {
			throw new Error(`Duplicate node code "${seed.code}"`);
		}

		const node: ContentNode = {
			id: nodes.length + 1,
			parentId,
			code: seed.code,
			type: seed.type ?? 'section',
			title: seed.title,
			text: seed.text ?? null,
			url: seed.url ?? null,
			targetId: null,
			image: seed.image ?? null,
			imageText: seed.imageText ?? null,
			tables: seed.tables ?? null,
			file: seed.file ?? null,
			fileName: seed.fileName ?? null,
			synonyms: seed.synonyms ?? [],
			sort,
			isActive: !seed.inactive,
			isHidden: Boolean(seed.hidden),
		};

		nodes.push(node);
		ids.set(seed.code, node.id);

		if (seed.target) {
			targets.push({ node, target: seed.target });
		}

		seed.children?.forEach((child, index) => walk(child, node.id, (index + 1) * 10));
	};

	walk(tree, null, 0);

	for (const { node, target } of targets) {
		const targetId = ids.get(target);

		if (!targetId) {
			throw new Error(`Node "${node.code}" points to unknown code "${target}"`);
		}

		node.targetId = targetId;
	}

	return nodes;
};
